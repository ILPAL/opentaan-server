-- Accounts as the game server keeps them.
--
-- The database hands out the ids, so two servers, or one server before and after a
-- restart, can never give out the same id twice. The first ids are the ones the
-- reference sessions record: account 1001 is player 1. Every value the client is sent
-- fits the 32-bit field it is sent in, and gender is male (1) or female (2).
--
-- The password is the hash the game server writes, in the text form its own code
-- defines and checks; the database only insists that one is given.

-- Rows written before this migration, by tests or by hand, are given player ids after
-- the highest one, so that the column can become required.
UPDATE accounts
SET player_id = numbered.player_id
FROM (
    SELECT account_id,
           (SELECT coalesce(max(player_id), 0) FROM accounts)
               + row_number() OVER (ORDER BY account_id) AS player_id
    FROM accounts
    WHERE player_id IS NULL
) AS numbered
WHERE accounts.account_id = numbered.account_id;

ALTER TABLE accounts ALTER COLUMN player_id SET NOT NULL;

ALTER TABLE accounts
    ALTER COLUMN account_id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1001),
    ALTER COLUMN player_id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ALTER COLUMN hashed_password DROP DEFAULT,
    ALTER COLUMN gender DROP DEFAULT,
    ADD COLUMN cash BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ADD CONSTRAINT account_id_fits_the_client CHECK (account_id BETWEEN 1 AND 4294967295),
    ADD CONSTRAINT player_id_fits_the_client CHECK (player_id BETWEEN 1 AND 4294967295),
    ADD CONSTRAINT cash_fits_the_client CHECK (cash BETWEEN 0 AND 4294967295),
    ADD CONSTRAINT gender_is_male_or_female CHECK (gender IN (1, 2));

-- Rows already there move the next id past them; with none, the ids start as above.
SELECT setval(pg_get_serial_sequence('accounts', 'account_id'), max(account_id) + 1, false)
FROM accounts
HAVING max(account_id) >= 1001;

SELECT setval(pg_get_serial_sequence('accounts', 'player_id'), max(player_id) + 1, false)
FROM accounts
HAVING max(player_id) >= 1;
