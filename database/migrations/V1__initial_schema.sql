-- Initial schema: 11 tables plus a version marker.
--
-- Flyway owns the schema. The game server and the admin server only check that
-- the schema matches; neither creates or alters tables. Never edit this file once
-- it has been applied anywhere: add V2, V3, ... instead.

-- Accounts and characters. Ids are allocated by the application (see `allocators`),
-- not by identity columns.
CREATE TABLE accounts (
    account_id      BIGINT PRIMARY KEY,
    email           TEXT   NOT NULL UNIQUE,
    hashed_password TEXT   NOT NULL DEFAULT '',
    gender          BIGINT NOT NULL DEFAULT 0,
    player_id       BIGINT UNIQUE
);

CREATE TABLE characters (
    character_id BIGINT PRIMARY KEY,
    account_id   BIGINT NOT NULL REFERENCES accounts(account_id) ON DELETE CASCADE,
    slot_index   BIGINT NOT NULL,
    name         TEXT   NOT NULL,
    name_key     TEXT   NOT NULL,
    info_json    TEXT   NOT NULL,
    appear_json  TEXT
);

CREATE UNIQUE INDEX characters_name_key ON characters(name_key);
CREATE INDEX characters_by_account ON characters(account_id, slot_index);

CREATE TABLE allocators (
    name  TEXT   PRIMARY KEY,
    value BIGINT NOT NULL
);

-- Per-account and global state, stored as JSON documents per family.
CREATE TABLE account_state (
    account_id BIGINT NOT NULL REFERENCES accounts(account_id) ON DELETE CASCADE,
    family     TEXT   NOT NULL,
    payload    TEXT   NOT NULL,
    PRIMARY KEY (account_id, family)
);

CREATE TABLE global_state (
    family  TEXT PRIMARY KEY,
    payload TEXT NOT NULL
);

-- Idempotency claims. The primary key is what makes a replay a no-op.
CREATE TABLE idempotency_claims (
    claim_key    TEXT   PRIMARY KEY,
    scope        TEXT   NOT NULL,
    character_id BIGINT,
    payload      TEXT,
    claimed_at   DOUBLE PRECISION NOT NULL,
    settled_at   DOUBLE PRECISION
);

CREATE INDEX idempotency_by_scope ON idempotency_claims(scope, character_id);

-- Shop ledger. One row per purchase or gift; the partial unique index makes a
-- retried request with the same idempotency key a no-op.
CREATE TABLE shop_transactions (
    transaction_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation       TEXT   NOT NULL,
    account_id      BIGINT,
    character_id    BIGINT NOT NULL,
    grant_item_id   BIGINT NOT NULL,
    item_def_id     BIGINT NOT NULL,
    quantity        BIGINT NOT NULL,
    price_claimed   BIGINT NOT NULL,
    charged         BIGINT NOT NULL DEFAULT 0,
    idempotency_key TEXT,
    created_at      DOUBLE PRECISION NOT NULL,
    UNIQUE(character_id, grant_item_id)
);

CREATE INDEX shop_transactions_by_character
    ON shop_transactions(character_id, created_at);

CREATE UNIQUE INDEX shop_transactions_idempotency
    ON shop_transactions(idempotency_key) WHERE idempotency_key IS NOT NULL;

-- Operators and the control-plane audit trail.
CREATE TABLE operators (
    operator_id   TEXT   PRIMARY KEY,
    display_name  TEXT   NOT NULL,
    secret        TEXT   NOT NULL,
    roles         TEXT   NOT NULL DEFAULT '',
    disabled      BIGINT NOT NULL DEFAULT 0,
    created_at    DOUBLE PRECISION NOT NULL,
    last_seen_at  DOUBLE PRECISION
);

CREATE TABLE control_audit (
    row_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_id       TEXT   NOT NULL,
    phase          TEXT   NOT NULL,
    correlation_id TEXT   NOT NULL,
    operator_id    TEXT   NOT NULL,
    service        TEXT   NOT NULL,
    command        TEXT   NOT NULL,
    subject        TEXT,
    request        TEXT   NOT NULL,
    status         TEXT,
    message        TEXT,
    created_at     DOUBLE PRECISION NOT NULL,
    UNIQUE(audit_id, phase)
);

CREATE INDEX control_audit_by_time     ON control_audit(created_at);
CREATE INDEX control_audit_by_operator ON control_audit(operator_id, created_at);
CREATE INDEX control_audit_by_command  ON control_audit(command, created_at);

-- Match history and per-player scoreboards.
CREATE TABLE matches (
    match_uid          BIGINT PRIMARY KEY,
    room_id            BIGINT NOT NULL,
    channel_id         BIGINT NOT NULL,
    game_type          BIGINT NOT NULL DEFAULT 0,
    map_id             BIGINT NOT NULL DEFAULT 0,
    mission_difficulty BIGINT,
    winning_team       BIGINT NOT NULL,
    duration_seconds   DOUBLE PRECISION NOT NULL DEFAULT 0,
    started_at         DOUBLE PRECISION,
    ended_at           DOUBLE PRECISION NOT NULL
);

CREATE INDEX matches_by_time    ON matches(ended_at);
CREATE INDEX matches_by_channel ON matches(channel_id, ended_at);

CREATE TABLE match_participants (
    match_uid          BIGINT NOT NULL
                       REFERENCES matches(match_uid) ON DELETE CASCADE,
    slot_index         BIGINT NOT NULL,
    character_id       BIGINT NOT NULL,
    character_name     TEXT   NOT NULL DEFAULT '',
    team               BIGINT NOT NULL DEFAULT 0,
    won                BIGINT NOT NULL DEFAULT 0,
    forfeited          BIGINT NOT NULL DEFAULT 0,

    kills              BIGINT NOT NULL DEFAULT 0,
    deaths             BIGINT NOT NULL DEFAULT 0,
    damage_dealt       BIGINT NOT NULL DEFAULT 0,
    support            BIGINT NOT NULL DEFAULT 0,
    assists            BIGINT NOT NULL DEFAULT 0,
    shots_fired        BIGINT NOT NULL DEFAULT 0,
    shots_hit          BIGINT NOT NULL DEFAULT 0,
    turns_taken        BIGINT NOT NULL DEFAULT 0,

    exp_gained         BIGINT NOT NULL DEFAULT 0,
    gold_gained        BIGINT NOT NULL DEFAULT 0,
    force_medal        BIGINT NOT NULL DEFAULT 0,
    kill_medal         BIGINT NOT NULL DEFAULT 0,
    support_medal      BIGINT NOT NULL DEFAULT 0,
    level_before       BIGINT NOT NULL DEFAULT 0,
    level_after        BIGINT NOT NULL DEFAULT 0,
    fatigue_multiplier DOUBLE PRECISION NOT NULL DEFAULT 1.0,

    PRIMARY KEY (match_uid, slot_index)
);

CREATE INDEX match_participants_by_character
    ON match_participants(character_id, match_uid);

-- Schema version marker, kept for compatibility with existing deployments that
-- read it. It stays at 6 for this baseline; Flyway tracks versions from here on.
CREATE TABLE schema_version (
    only_row BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (only_row),
    version  BIGINT NOT NULL
);

