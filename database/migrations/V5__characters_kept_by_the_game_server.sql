-- Characters as the game server keeps them, and whether each has finished the tutorial.
--
-- What the server changes about a character is a column of its own, checked to fit the
-- field the client is sent it in. What can be worked out from other values is not
-- stored: the experience bar comes from the level, the gender from the account, and
-- the two appearance fields that carry the id and the level from those columns. The
-- JSON copies of what the client was sent are dropped; nothing ever read them.
--
-- The database hands out the ids, from 1001 as the reference sessions record. An
-- account has one character, as in the client, which offers to create one only for an
-- account without. Names are unique on the key the game server computes for them,
-- since the two names that key folds together are one name to the client.

ALTER TABLE characters
    ALTER COLUMN character_id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1001),
    DROP COLUMN info_json,
    DROP COLUMN appear_json,
    ADD COLUMN level          INTEGER     NOT NULL DEFAULT 1,
    ADD COLUMN experience     BIGINT      NOT NULL DEFAULT 0,
    ADD COLUMN gold           BIGINT      NOT NULL DEFAULT 0,
    ADD COLUMN rank_placement BIGINT      NOT NULL DEFAULT 0,
    ADD COLUMN rank_score     BIGINT      NOT NULL DEFAULT 0,
    ADD COLUMN league_money   BIGINT      NOT NULL DEFAULT 0,
    ADD COLUMN soul_points    BIGINT      NOT NULL DEFAULT 0,
    ADD COLUMN wins           BIGINT      NOT NULL DEFAULT 0,
    ADD COLUMN losses         BIGINT      NOT NULL DEFAULT 0,
    ADD COLUMN force_medals   BIGINT      NOT NULL DEFAULT 0,
    ADD COLUMN kill_medals    BIGINT      NOT NULL DEFAULT 0,
    ADD COLUMN support_medals BIGINT      NOT NULL DEFAULT 0,
    -- When the character reached the end of the tutorial, or NULL while it has not. The
    -- client keeps no record of it, so this is all that stops the tutorial coming back.
    ADD COLUMN tutorial_finished_at TIMESTAMPTZ,
    ADD COLUMN created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    ADD CONSTRAINT character_id_fits_the_client CHECK (character_id BETWEEN 1 AND 4294967295),
    ADD CONSTRAINT name_fits_the_client CHECK (char_length(name) BETWEEN 4 AND 16),
    ADD CONSTRAINT level_fits_the_client CHECK (level BETWEEN 1 AND 65535),
    ADD CONSTRAINT counts_fit_the_client CHECK (
        experience     BETWEEN 0 AND 4294967295
        AND gold           BETWEEN 0 AND 4294967295
        AND rank_placement BETWEEN 0 AND 4294967295
        AND rank_score     BETWEEN 0 AND 4294967295
        AND league_money   BETWEEN 0 AND 4294967295
        AND soul_points    BETWEEN 0 AND 4294967295
        AND wins           BETWEEN 0 AND 4294967295
        AND losses         BETWEEN 0 AND 4294967295
        AND force_medals   BETWEEN 0 AND 4294967295
        AND kill_medals    BETWEEN 0 AND 4294967295
        AND support_medals BETWEEN 0 AND 4294967295
    );

CREATE UNIQUE INDEX characters_one_per_account ON characters (account_id);

-- Rows already there move the next id past them; with none, the ids start as above.
SELECT setval(pg_get_serial_sequence('characters', 'character_id'), max(character_id) + 1, false)
FROM characters
HAVING max(character_id) >= 1001;

-- The parts a character wears, by their place in its appearance. A part with nothing in
-- it is no row, so a character fresh from the creator has a row for each part it chose.
CREATE TABLE character_parts (
    character_id BIGINT   NOT NULL REFERENCES characters (character_id) ON DELETE CASCADE,
    part         SMALLINT NOT NULL CHECK (part BETWEEN 0 AND 15),
    item_id      BIGINT   NOT NULL CHECK (item_id BETWEEN 0 AND 4294967295),
    variant1     INTEGER  NOT NULL CHECK (variant1 BETWEEN 0 AND 65535),
    variant2     INTEGER  NOT NULL CHECK (variant2 BETWEEN 0 AND 65535),
    variant3     INTEGER  NOT NULL CHECK (variant3 BETWEEN 0 AND 65535),
    PRIMARY KEY (character_id, part),
    CONSTRAINT an_empty_part_is_no_row CHECK (item_id <> 0 OR variant1 <> 0 OR variant2 <> 0 OR variant3 <> 0)
);
